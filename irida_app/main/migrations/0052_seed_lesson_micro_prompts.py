def seed_micro_prompts(apps, schema_editor):
    AIPrompt = apps.get_model('main', 'AIPrompt')

    for prompt_data in NEW_PROMPTS:
        prompt_obj = AIPrompt.objects.filter(
            page_key=prompt_data['page_key'],
            title=prompt_data['title']
        ).first()

        if prompt_obj:
            prompt_obj.prompt_text = prompt_data['prompt_text']
            prompt_obj.instructions = prompt_data['instructions']
            prompt_obj.order = prompt_data['order']
            prompt_obj.is_system = True
            prompt_obj.save()
        else:
            AIPrompt.objects.create(**prompt_data)

    # Актуализираме поредността (order) на всички системни промптове за lesson_main
    for title, order_num in ORDER_MAPPING.items():
        AIPrompt.objects.filter(page_key='lesson_main', title=title, is_system=True).update(order=order_num)


